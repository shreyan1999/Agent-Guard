/**
 * Governance pipeline variants.
 *
 * Five views of the same system, one picked per visit to Overview. They are
 * not re-skins of one layout: each has its own *shape*, because five boards
 * that all read left-to-right along one row look like the same picture with
 * the words swapped.
 *
 *   1 · lifecycle   — an orbit. The request goes round and comes back.
 *   2 · outcomes    — a fork. Two tracks that split and never rejoin.
 *   3 · identity    — a rising staircase, ending in a two-way branch.
 *   4 · onboarding  — a serpentine. Right along the top, back along the bottom.
 *   5 · reliability — a closed hexagonal circuit with a hub in the middle.
 *
 * Every variant shares one 980x272 board so the card never has to resize, and
 * every path is generated by the helpers below rather than hand-written — the
 * hand-written version drifted a few units per edge and the joins stopped
 * meeting the node boxes cleanly.
 */

