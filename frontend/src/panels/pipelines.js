/**
 * Rotates through the variants so a different one appears each time Overview
 * is opened. Module-level state, deliberately: it has to survive the panel
 * unmounting when you switch tabs, which is exactly when it needs to advance.
 */
let cursor = Math.floor(Math.random() * PIPELINES.length);

export function nextPipeline() {
  cursor = (cursor + 1) % PIPELINES.length;
  return PIPELINES[cursor];
}

