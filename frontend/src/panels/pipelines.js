export const BOARD = { w: 980, h: 272 };
export const NODE_R = 30;

const R = NODE_R;
const GAP = R + 9;          // where an edge stops short of a node box
const C = 16;               // corner radius on every elbow
const r1 = n => Math.round(n * 10) / 10;

/* ── path helpers ────────────────────────────────────────────────────────── */

/** Straight run between two nodes on the same row. */
const row = (a, b, y) => `M ${a + R} ${y} H ${b - R}`;

/** Straight run between two nodes in the same column. */
const col = (y1, y2, x) => `M ${x} ${y1 + R} V ${y2 - R}`;

/** A diagonal, trimmed at both ends so it meets the node boxes. */
const diag = (a, b) => {
  const dx = b.x - a.x;
  const dy = b.y - a.y;
  const L = Math.hypot(dx, dy) || 1;
  const ux = dx / L;
  const uy = dy / L;
  return `M ${r1(a.x + ux * GAP)} ${r1(a.y + uy * GAP)}`
    + ` L ${r1(b.x - ux * GAP)} ${r1(b.y - uy * GAP)}`;
};

/** Row `ay` out to a node on row `by`, turning at `mx`. */
const elbow = (a, ay, b, by, mx) => {
  const d = by < ay ? -1 : 1;
  return `M ${a + R} ${ay} H ${mx - C} Q ${mx} ${ay} ${mx} ${ay + d * C}`
    + ` V ${by - d * C} Q ${mx} ${by} ${mx + C} ${by} H ${b - R}`;
};

/** A U-turn off the right edge: row `ay` at `a`, round `x`, back into `b` on row `by`. */
const uTurnRight = (a, ay, b, by, x) =>
  `M ${a + R} ${ay} H ${x - C} Q ${x} ${ay} ${x} ${ay + C}`
  + ` V ${by - C} Q ${x} ${by} ${x - C} ${by} H ${b + R}`;

/** The mirror: off the left edge and back. */
const uTurnLeft = (a, ay, b, by, x) =>
  `M ${a - R} ${ay} H ${x + C} Q ${x} ${ay} ${x} ${ay - C}`
  + ` V ${by + C} Q ${x} ${by} ${x + C} ${by} H ${b - R}`;

/* ── the orbit, used by variant 1 ────────────────────────────────────────── */

const ORBIT = { cx: 490, cy: 130, rx: 366, ry: 86 };

const orbitAt = (deg) => {
  const t = (deg * Math.PI) / 180;
  return {
    x: ORBIT.cx + ORBIT.rx * Math.cos(t),
    y: ORBIT.cy - ORBIT.ry * Math.sin(t),   // screen y grows downward
  };
};

/**
 * An arc along the orbit from one node to the next, trimmed at both ends.
 * The trim is walked rather than computed from a fixed angle: on an ellipse
 * this eccentric, the same angular step covers 84px near the poles and 372px
 * at the sides, so a constant offset leaves one end buried and the other adrift.
 */
const orbitArc = (from, to) => {
  const dir = Math.sign(to - from) || -1;
  const A = orbitAt(from);
  const B = orbitAt(to);
  const far = (p, q) => Math.hypot(p.x - q.x, p.y - q.y) >= GAP;
  let a = from;
  let b = to;
  while (!far(orbitAt(a), A) && Math.abs(a - from) < 90) a += dir * 0.5;
  while (!far(orbitAt(b), B) && Math.abs(b - to) < 90) b -= dir * 0.5;
  const p = orbitAt(a);
  const q = orbitAt(b);
  // Travelling by decreasing angle is clockwise on screen, which is sweep 1.
  return `M ${r1(p.x)} ${r1(p.y)} A ${ORBIT.rx} ${ORBIT.ry} 0 0 1 ${r1(q.x)} ${r1(q.y)}`;
};

/* ── 1 · the round trip ──────────────────────────────────────────────────── */

/**
 * Seven stops around the orbit, spaced by *arc length* rather than by angle.
 * On an ellipse this flat, equal angular steps bunch two nodes almost on top
 * of each other at each pole — 51 degrees covers 330px along the top and only
 * 75px at the ends — so the boxes overlap and a label lands on the node below
 * it. Walking the perimeter instead spreads them evenly in the way the eye
 * actually reads.
 */
const ORBIT_ARC = (() => {
  const STEPS = 2400;
  const pts = [];
  const cum = [0];
  for (let i = 0; i <= STEPS; i++) {
    const deg = 180 - (360 * i) / STEPS;       // decreasing = clockwise on screen
    const q = orbitAt(deg);
    pts.push({ deg, ...q });
    if (i) cum.push(cum[i - 1] + Math.hypot(q.x - pts[i - 1].x, q.y - pts[i - 1].y));
  }
  return { pts, cum, total: cum[STEPS] };
})();

const degAtArc = (s) => {
  const { pts, cum, total } = ORBIT_ARC;
  const target = ((s % total) + total) % total;
  let lo = 0;
  let hi = cum.length - 1;
  while (lo < hi - 1) {
    const mid = (lo + hi) >> 1;
    if (cum[mid] <= target) lo = mid; else hi = mid;
  }
  return pts[lo].deg;
};

